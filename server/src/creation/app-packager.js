import {
  createFallbackAppDefinition,
  createFallbackInteractiveApp
} from "./deterministic-app.js";
import { createZip } from "./zip.js";
import { buildDocumentArtifactSet } from "./document-export.js";

const safeName = (value, fallback = "iabt-deliverable") =>
  String(value || fallback)
    .replace(/[\\/:*?"<>|]+/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 140) || fallback;

const slug = (value) =>
  safeName(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80) || "iabt-application";

const validate = (html, requestText) => {
  const request = String(requestText || "").toLowerCase();
  const checks = [
    { check: "html_complete", passed: /<!doctype\s+html/i.test(html) && /<\/html>/i.test(html) },
    { check: "inline_styles", passed: /<style\b/i.test(html) },
    { check: "no_external_scripts", passed: !/<script\b[^>]*\bsrc\s*=/i.test(html) },
    { check: "no_external_assets", passed: !/(?:src|href|action)\s*=\s*["']https?:\/\//i.test(html) }
  ];
  if (/piano|keyboard instrument|web audio/.test(request)) {
    checks.push(
      { check: "piano_audio_engine", passed: /AudioContext|webkitAudioContext/.test(html) },
      { check: "keyboard_press", passed: /keydown/i.test(html) },
      { check: "keyboard_release", passed: /keyup/i.test(html) },
      { check: "octave_controls", passed: /octave/i.test(html) }
    );
  }
  if (/merch|store|shop|e-?commerce|sell products/.test(request)) {
    checks.push(
      { check: "product_catalog", passed: /product|merchandise/i.test(html) },
      { check: "cart_add", passed: /add.{0,12}cart/i.test(html) },
      { check: "cart_quantities", passed: /data-change|quantity|qty/i.test(html) },
      { check: "subtotal", passed: /subtotal|total/i.test(html) },
      { check: "checkout_boundary", passed: /checkout/i.test(html) && /preview|stripe|payment/i.test(html) }
    );
  }
  return {
    status: checks.every((check) => check.passed) ? "passed" : "failed",
    checks
  };
};

export const buildInteractiveArtifacts = ({ title, requestText, spec = {} }) => {
  const definition = createFallbackAppDefinition(requestText, spec);
  const implementation = createFallbackInteractiveApp(requestText, spec, definition);
  const validation = validate(implementation.preview_html, requestText);
  if (validation.status !== "passed") {
    throw Object.assign(new Error("Generated interactive output failed request-specific validation"), {
      code: "interactive_validation_failed"
    });
  }

  const packageName = slug(definition.app?.name || title);
  const sourceFiles = {
    "package.json": JSON.stringify({
      name: packageName,
      private: true,
      version: "1.0.0",
      type: "module",
      scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
      dependencies: { react: "^18.3.1", "react-dom": "^18.3.1" },
      devDependencies: { "@vitejs/plugin-react": "^4.3.4", vite: "^6.0.0" }
    }, null, 2),
    "index.html": "<!doctype html><html><head><meta charset=\"UTF-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1.0\"><title>" + safeName(title) + "</title></head><body><div id=\"root\"></div><script type=\"module\" src=\"/src/main.jsx\"></script></body></html>",
    "src/main.jsx": "import React from \"react\";\nimport ReactDOM from \"react-dom/client\";\nimport App from \"./App.jsx\";\nimport \"./styles.css\";\nReactDOM.createRoot(document.getElementById(\"root\")).render(<React.StrictMode><App /></React.StrictMode>);\n",
    "src/App.jsx": "import React from \"react\";\nexport default function App(){return <iframe className=\"iabt-frame\" title=" + JSON.stringify(safeName(title)) + " src=\"/app.html\" />;}\n",
    "src/styles.css": "*{box-sizing:border-box}html,body,#root{width:100%;height:100%;margin:0}.iabt-frame{display:block;width:100%;height:100vh;border:0}",
    "public/app.html": implementation.preview_html,
    "iabt-app-definition.json": JSON.stringify(definition, null, 2),
    "BUILD_REPORT.json": JSON.stringify({
      generated_at: new Date().toISOString(),
      product: "Intelligent Application Building Tool (IABT)",
      generation_strategy: implementation.generation_strategy,
      source_integrity: "passed",
      interactive_validation: validation,
      test_cases: implementation.test_cases,
      production_build: {
        status: "not_run",
        command: "npm install && npm run build",
        note: "Run the included production build before public deployment."
      }
    }, null, 2),
    "README.md": "# " + safeName(title) + "\n\nGenerated by IABT JERICHO Studio.\n\nRun:\n\n    npm install\n    npm run dev\n\nVerify:\n\n    npm run build\n"
  };
  const report = JSON.parse(sourceFiles["BUILD_REPORT.json"]);
  const zip = createZip(sourceFiles);

  return {
    metadata: {
      generation_strategy: implementation.generation_strategy,
      validation_status: validation.status,
      artifact_count: 4
    },
    artifacts: [
      {
        bytes: Buffer.from(implementation.preview_html, "utf8"),
        contentType: "text/html; charset=utf-8",
        filename: safeName(title) + " - Interactive Preview.html",
        kind: "app",
        metadata: { interactive: true, preview_ready: true, validation_status: validation.status }
      },
      {
        bytes: Buffer.from(JSON.stringify(definition, null, 2), "utf8"),
        contentType: "application/vnd.iabt+json",
        filename: safeName(title) + " - AppDefinition.json",
        kind: "app",
        metadata: { builder_ready: true, page_count: definition.pages.length }
      },
      {
        bytes: zip,
        contentType: "application/zip",
        filename: packageName + "-source.zip",
        kind: "archive",
        metadata: { source_integrity: "passed", file_count: Object.keys(sourceFiles).length }
      },
      {
        bytes: Buffer.from(JSON.stringify(report, null, 2), "utf8"),
        contentType: "application/json",
        filename: safeName(title) + " - BUILD_REPORT.json",
        kind: "document",
        metadata: { source_integrity: "passed" }
      }
    ]
  };
};

export const buildDocumentArtifacts = ({ title, requestText, intent }) => {
  const heading = intent === "audio"
    ? "Audio Preproduction Package"
    : intent === "video"
      ? "Video Preproduction Package"
      : safeName(title);
  const markdown = [
    "# " + heading,
    "",
    "Generated by IABT JERICHO Studio",
    "",
    "## Objective",
    "",
    String(requestText || "").trim(),
    "",
    "## Production status",
    "",
    intent === "audio"
      ? "This is a production specification. No playable audio is claimed unless an approved audio renderer creates and verifies an MP3 artifact."
      : intent === "video"
        ? "This is a production specification. No playable video is claimed until asynchronous rendering and media verification complete."
        : "This document was generated and stored as a durable Markdown artifact.",
    "",
    "## Verification",
    "",
    "- The request is preserved with the deliverable.",
    "- The file is stored privately.",
    "- The IABT credit is captured only after durable storage succeeds."
  ].join("\n");
  return buildDocumentArtifactSet({
    title: safeName(title),
    markdown
  });
};