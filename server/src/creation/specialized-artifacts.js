import { createZip } from "./zip.js";

const safeName = (value, fallback = "JERICHO Deliverable") =>
  String(value || fallback)
    .replace(/[\\/:*?"<>|]+/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120) || fallback;

const slug = (value, fallback) =>
  safeName(value, fallback)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 72) || fallback;

const artifact = (bytes, contentType, filename, kind, metadata = {}) => ({
  bytes: Buffer.isBuffer(bytes) ? bytes : Buffer.from(String(bytes), "utf8"),
  contentType,
  filename,
  kind,
  metadata
});

const json = (value) => JSON.stringify(value, null, 2) + "\n";

const escapeXml = (value) =>
  String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");

